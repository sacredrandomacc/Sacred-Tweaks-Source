CREATE UNIQUE INDEX IF NOT EXISTS username_casefold ON users(lower(username));
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, events DOUBLE PRECISION[] NOT NULL, expires_at DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS rate_limits_expiry ON rate_limits(expires_at);
