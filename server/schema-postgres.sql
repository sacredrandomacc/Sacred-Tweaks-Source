CREATE TABLE IF NOT EXISTS licenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key_hash TEXT NOT NULL UNIQUE, key_hint TEXT NOT NULL,
 tier TEXT NOT NULL, duration_days DOUBLE PRECISION, created_at DOUBLE PRECISION NOT NULL,
 redeemed_at DOUBLE PRECISION, expires_at DOUBLE PRECISION, status TEXT NOT NULL DEFAULT 'active',
 overrides TEXT NOT NULL DEFAULT '{}', enforced TEXT NOT NULL DEFAULT '{}',
 welcome TEXT NOT NULL DEFAULT '{}', replaced_by BIGINT REFERENCES licenses(id)
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL,
 password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'member',
 license_id BIGINT UNIQUE REFERENCES licenses(id), created_at DOUBLE PRECISION NOT NULL,
 device_hash TEXT, banned INTEGER NOT NULL DEFAULT 0, ban_until DOUBLE PRECISION, ban_reason TEXT,
 totp_secret TEXT, totp_last_step INTEGER NOT NULL DEFAULT -1,
 last_transfer_at DOUBLE PRECISION, last_reset_at DOUBLE PRECISION
);
CREATE UNIQUE INDEX IF NOT EXISTS sole_owner ON users(role) WHERE role='owner';
CREATE TABLE IF NOT EXISTS sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash TEXT NOT NULL UNIQUE,
 user_id BIGINT NOT NULL REFERENCES users(id), created_at DOUBLE PRECISION NOT NULL,
 renewed_at DOUBLE PRECISION NOT NULL, lease_until DOUBLE PRECISION NOT NULL, absolute_until DOUBLE PRECISION NOT NULL,
 revoked INTEGER NOT NULL DEFAULT 0, snapshot TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_session ON sessions(user_id) WHERE revoked=0;
CREATE TABLE IF NOT EXISTS recovery_codes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 code_hash TEXT NOT NULL UNIQUE, used_at DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS reset_credentials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 token_hash TEXT NOT NULL UNIQUE, expires_at DOUBLE PRECISION NOT NULL, used_at DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS devices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 device_hash TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL, removed_at DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS transfers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 device_hash TEXT NOT NULL, reason TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending', resolved_at DOUBLE PRECISION, resolved_by BIGINT REFERENCES users(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS pending_transfer ON transfers(user_id) WHERE status='pending';
CREATE TABLE IF NOT EXISTS profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 name TEXT NOT NULL, config TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL,
 UNIQUE(user_id,name)
);
CREATE TABLE IF NOT EXISTS content (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, name TEXT NOT NULL,
 body TEXT NOT NULL, channel TEXT NOT NULL, tier TEXT, version INTEGER NOT NULL,
 created_at DOUBLE PRECISION NOT NULL, author_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS feedback (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 message TEXT NOT NULL, diagnostics TEXT, created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT REFERENCES users(id),
 action TEXT NOT NULL, target_type TEXT NOT NULL, target_id BIGINT,
 details TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id),
 kind TEXT NOT NULL, message TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
